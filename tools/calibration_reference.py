"""Write the reference the playground's device check compares against.

    python tools/calibration_reference.py        # -> web/js/engine/calibration-reference.js

On its first visit the playground synthesises one short sentence on every
backend it can use, times each run, and checks the audio against this file:
the same phonemes, the noise switched off (``noise_scale`` 0), so the output is
deterministic. A backend whose audio has a different length, level or shape
from onnxruntime's on the CPU here is computing something else -- which is
what WebGPU did on a Redmi Note 10 Pro -- and is not used.

Rerun it whenever ``web/onnx/`` changes: the file carries a hash of the graphs,
and a visitor whose stored result names another hash is measured again.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Sequence

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from aztts.console import use_utf8  # noqa: E402

use_utf8()

ONNX_DIR = PROJECT_ROOT / "web" / "onnx"
OUT = PROJECT_ROOT / "web" / "js" / "engine" / "calibration-reference.js"
SYMBOLS = PROJECT_ROOT / "model" / "symbols.json"

# Short on purpose: a phone's browser runs it several times on its first visit.
# About 1.3 s of speech. Language data, with the phonemes eSpeak NG gives it,
# so the check does not depend on the phonemiser having loaded.
TEXT = "Salam, dünya."
PHONEMES = "saɫˈam, dynjˈa."

SAMPLE_RATE = 24000
WINDOW = 1200  # 50 ms: the loudness envelope's resolution
DECODERS = {"fp32": "decode.onnx", "int8": "decode.int8.onnx"}


def tokenise(phonemes: str, symbols: Sequence[str]) -> list[int]:
    """The same ids as web/js/engine/inputs.js: a blank (0) around every symbol."""
    ids = {symbol: index for index, symbol in enumerate(symbols)}
    known = [ids[character] for character in phonemes if character in ids]
    spread = [0] * (2 * len(known) + 1)
    spread[1::2] = known
    return spread


def envelope(waveform: Sequence[float], window: int = WINDOW) -> list[float]:
    """RMS per window, whole windows only -- as fingerprint.js computes it."""
    count = len(waveform) // window
    levels = []
    for index in range(count):
        part = waveform[index * window:(index + 1) * window]
        levels.append((sum(value * value for value in part) / window) ** 0.5)
    return levels


def rms(waveform: Sequence[float]) -> float:
    return (sum(value * value for value in waveform) / len(waveform)) ** 0.5 if waveform else 0.0


def graphs_hash(paths: Sequence[Path]) -> str:
    digest = hashlib.sha256()
    for path in paths:
        digest.update(path.read_bytes())
    return digest.hexdigest()[:16]


def synthesise(onnx_dir: Path, decoder: str, tokens: list[int]) -> list[float]:
    import numpy as np
    import onnxruntime as ort

    duration = ort.InferenceSession(str(onnx_dir / "duration.onnx"))
    decode = ort.InferenceSession(str(onnx_dir / decoder))
    mean, logs, mask = duration.run(None, {
        "tokens": np.array([tokens], np.int64),
        "lengths": np.array([len(tokens)], np.int64),
        "length_scale": np.array(1.0, np.float32),
    })
    waveform = decode.run(None, {
        "m_p_exp": mean,
        "logs_p_exp": logs,
        "y_mask": mask,
        "zp_noise": np.zeros_like(mean),
        "noise_scale": np.array(0.0, np.float32),
    })[0]
    return [float(value) for value in waveform.ravel()]


def fingerprint(waveform: Sequence[float]) -> dict:
    return {
        "samples": len(waveform),
        "rms": round(rms(waveform), 7),
        "envelope": [round(level, 6) for level in envelope(waveform)],
    }


def render(reference: dict) -> str:
    body = json.dumps(reference, ensure_ascii=False, indent=2)
    return (
        "/**\n"
        " * Generated by tools/calibration_reference.py -- do not edit by hand.\n"
        " *\n"
        " * What onnxruntime on the CPU produces for the device check's sentence with\n"
        " * the noise switched off; js/engine/fingerprint.js compares a backend's\n"
        " * output with it. `version` is a hash of the graphs it was made from.\n"
        " */\n\n"
        f"export const REFERENCE = Object.freeze({body});\n"
    )


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--onnx", type=Path, default=ONNX_DIR, help="the playground's graphs")
    parser.add_argument("--out", type=Path, default=OUT, help="the module to write")
    args = parser.parse_args(argv)

    symbols = json.loads(SYMBOLS.read_text(encoding="utf-8"))["symbols"]
    tokens = tokenise(PHONEMES, symbols)
    paths = [args.onnx / "duration.onnx", *(args.onnx / name for name in DECODERS.values())]
    missing = [str(path) for path in paths if not path.exists()]
    if missing:
        print(f"missing graphs: {', '.join(missing)}", file=sys.stderr)
        return 1

    reference = {
        "version": graphs_hash(paths),
        "text": TEXT,
        "phonemes": PHONEMES,
        "sampleRate": SAMPLE_RATE,
        "window": WINDOW,
        **{name: fingerprint(synthesise(args.onnx, file, tokens)) for name, file in DECODERS.items()},
    }
    args.out.write_text(render(reference), encoding="utf-8", newline="\n")
    print(f"wrote {args.out} ({reference['fp32']['samples']} samples, version {reference['version']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
